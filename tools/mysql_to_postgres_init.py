def split_sql_items(block: str) -> list[str]:
    items: list[str] = []
    current: list[str] = []
    quote: str | None = None
    depth = 0
    for ch in block:
        if quote:
            current.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in ("'", '"', "`"):
            quote = ch
            current.append(ch)
            continue
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            item = "".join(current).strip()
            if item:
                items.append(item)
            current = []
        else:
            current.append(ch)
    item = "".join(current).strip()
    if item:
        items.append(item)
    return items


def strip_mysql_comment(item: str) -> str:
    return re.sub(r"\s+comment\s+'(?:''|[^'])*'", "", item, flags=re.I)


def convert_type(definition: str) -> tuple[str, str | None]:
    item = strip_mysql_comment(definition.strip().rstrip(","))
    item = item.replace("`", "")
    auto_increment = bool(re.search(r"\bauto_increment\b", item, flags=re.I))
    item = re.sub(r"\bauto_increment\b", "", item, flags=re.I)
    item = re.sub(r"\bbigint\s*\(\s*\d+\s*\)", "bigint", item, flags=re.I)
    item = re.sub(r"\bint\s*\(\s*\d+\s*\)", "integer", item, flags=re.I)
    item = re.sub(r"\btinyint\s*\(\s*1\s*\)", "smallint", item, flags=re.I)
    item = re.sub(r"\bsmallint\s*\(\s*\d+\s*\)", "smallint", item, flags=re.I)
    item = re.sub(r"\bdatetime\b", "timestamp", item, flags=re.I)
    item = re.sub(r"\blongtext\b", "text", item, flags=re.I)
    item = re.sub(r"\blongblob\b", "text", item, flags=re.I)
    item = re.sub(r"\bblob\b", "bytea", item, flags=re.I)
    item = re.sub(r"\bdouble\s*\(\s*\d+\s*,\s*\d+\s*\)", "double precision", item, flags=re.I)
    item = re.sub(r"\s+", " ", item).strip()

    column = item.split()[0]
    sequence_sql = None
    if auto_increment:
        seq = f"{column}_seq"
        item = re.sub(r"\bbigint\b", f"bigint generated by default as identity", item, count=1, flags=re.I)
        item = re.sub(r"\binteger\b", f"integer generated by default as identity", item, count=1, flags=re.I)
    return item, sequence_sql


def convert_create_table(match: re.Match[str]) -> str:
    table = match.group("table").replace("`", "")
    body = match.group("body")
    items = split_sql_items(body)
    converted: list[str] = []
    extra_indexes: list[str] = []

    for item in items:
        raw = item.strip()
        lower = raw.lower()
        if lower.startswith("primary key"):
            converted.append(raw.replace("`", ""))
        elif lower.startswith("unique key"):
            clean = strip_mysql_comment(raw).replace("`", "")
            m = re.match(r"unique\s+key\s+(\w+)\s*\((.+)\)", clean, flags=re.I)
            if m:
                extra_indexes.append(f"CREATE UNIQUE INDEX {m.group(1)} ON {table} ({m.group(2)});")
        elif lower.startswith(("key ", "index ")):
            clean = strip_mysql_comment(raw).replace("`", "")
            m = re.match(r"(?:key|index)\s+(\w+)\s*\((.+)\)", clean, flags=re.I)
            if m:
                extra_indexes.append(f"CREATE INDEX {m.group(1)} ON {table} ({m.group(2)});")
        else:
            col, _ = convert_type(raw)
            converted.append(col)

    table_sql = "DROP TABLE IF EXISTS " + table + " CASCADE;\n"
    table_sql += "CREATE TABLE " + table + " (\n  "
    table_sql += ",\n  ".join(converted)
    table_sql += "\n);\n"
    if extra_indexes:
        table_sql += "\n" + "\n".join(extra_indexes) + "\n"
    return table_sql


