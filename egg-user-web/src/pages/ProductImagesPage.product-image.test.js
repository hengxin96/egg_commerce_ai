test('product image rewrite validates the active requirement field before opening dialog', () => {
  const page = readSource('./ProductImagesPage.vue')

  assert.match(page, /const rewriteRequirement = form\.prompt\?\.trim\(\) \|\| ''/)
  assert.match(page, /const rewriteRequirementLabel = `\$\{form\.assetType \|\| '主图'\}要求`/)
  assert.match(page, /ElMessage\.warning\(`\$\{rewriteRequirementLabel\}不能为空`\)/)
  assert.match(page, /if \(!rewriteRequirement\) \{[\s\S]*ElMessage\.warning\(`\$\{rewriteRequirementLabel\}不能为空`\)[\s\S]*return[\s\S]*\}[\s\S]*rewriteDialogVisible\.value = true/s)
  assert.match(page, /userRequirement:\s*rewriteRequirement/)
  const rewritePayload = page.match(/await rewriteProductRequirementStream\(\{([\s\S]*?)\}, \{/)[1]
  assert.match(rewritePayload, /targetPlatform:\s*form\.platform/)
  assert.match(rewritePayload, /userRequirement:\s*rewriteRequirement/)
  assert.doesNotMatch(rewritePayload, /productAssetId|assetType|targetLanguage|textEnabled|imageCount|selectedModel|aspectRatio|quality/)
  assert.doesNotMatch(page, /用户需求不能为空/)
})

